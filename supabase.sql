-- Run in a separate Supabase demonstration project. All visitors share test tasks.
begin;
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) between 1 and 200),
  description text check (length(description) <= 10000),
  completed boolean not null default false
);
alter table public.tasks enable row level security;
grant usage on schema public to anon;
grant select, insert, update, delete on public.tasks to anon;
grant usage, select on sequence public.tasks_id_seq to anon;
drop policy if exists "Public demo read" on public.tasks;
drop policy if exists "Public demo create" on public.tasks;
drop policy if exists "Public demo update" on public.tasks;
drop policy if exists "Public demo delete" on public.tasks;
create policy "Public demo read" on public.tasks for select to anon using (true);
create policy "Public demo create" on public.tasks for insert to anon with check (true);
create policy "Public demo update" on public.tasks for update to anon using (true) with check (true);
create policy "Public demo delete" on public.tasks for delete to anon using (true);
commit;
